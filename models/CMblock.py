    def forward(self, x: torch.Tensor, **kwargs):

        x = x.float() 
        # print("x",x.shape)
        x_ln = self.in_norm(x)

        # --- NEW: wavelet front-end ---
        x_gated, gate_map = self.sgate(x_ln)
            # [B, d_model, H, W]
        # If you want to use only the wavelet output: x_in = x_wave

        branch = self.branch_conv1(x_gated)
        B, C, H, W = x_gated.shape
        # The SS2D branch also uses the same front-end features x_in
        x_proj_input = x_ln.permute(0, 2, 3, 1).contiguous()
        xz = self.in_proj(x_proj_input)
        x, z = xz.chunk(2, dim=-1) # (b, h, w, d), split into two parts
        x = x.permute(0, 3, 1, 2).contiguous()
        
        x = self.act(x) # (b, d, h, w), apply the SiLU activation
        y1, y2, y3, y4 = self.forward_core(x) # Pass through the SS2D module
        assert y1.dtype == torch.float32
        y = y1 + y2 + y3 + y4
        y = torch.transpose(y, dim0=1, dim1=2).contiguous().view(B, H, W, -1)

        y = self.out_norm(y)                     # normalized_shape=64

        y = y * F.silu(z) # Apply the Hadamard product
        out3 = self.out_proj(y)
        o2 = branch          # [B, d_model, H, W]
        o3 = out3.permute(0, 3, 1, 2)  # [B, d_model, H, W]
        # 1) Concatenate along the channel dimension
        fused = torch.cat([o2, o3], dim=1)  # [B, 2*d_model, H, W]
        if self.dropout is not None:
            fused = self.dropout(fused)
        return fused



