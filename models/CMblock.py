# Learnable wavelet transform
class SpatialGate(nn.Module):
    """
    Spatial-domain adaptive gating
    - Pure spatial modeling
    - No frequency assumption
    - Residual-safe (0.5 + 0.5 * gate)
    """
    def __init__(self, c, k=7):
        super().__init__()
        self.dwconv = nn.Conv2d(
            c, c, kernel_size=k, padding=k // 2, groups=c, bias=False
        )
        self.pwconv = nn.Sequential(
            nn.Conv2d(c, max(8, c // 2), 1),
            nn.ReLU(inplace=True),
            nn.Conv2d(max(8, c // 2), c, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        # local spatial context
        s = self.dwconv(x)
        w = self.pwconv(s)
        return x * (0.5 + 0.5 * w), w

class DropPath(nn.Module):
    """Stochastic Depth / DropPath"""
    def __init__(self, drop_prob: float = 0.0):
        super().__init__()
        self.drop_prob = drop_prob
    def forward(self, x):
        if self.drop_prob == 0.0 or not self.training:
            return x
        keep = 1.0 - self.drop_prob
        shape = (x.shape[0],) + (1,) * (x.ndim - 1)
        mask = torch.empty(shape, device=x.device).bernoulli_(keep)
        return x * mask / keep


